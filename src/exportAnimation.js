import { compileTimeline } from './compileTimeline.js';
import { exportRuntime } from './exportRuntime.js';

// Only receives the validated schema snapshot below, never caller-owned objects
// or their toJSON hooks. Number literals round-trip, including negative zero.
function serialize(value) {
  if (typeof value === 'number') return Object.is(value, -0) ? '-0' : String(value);
  if (typeof value === 'string') {
    return JSON.stringify(value).replace(/[<>&\u2028\u2029]/g,
      (character) => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);
  }
  if (Array.isArray(value)) return `[${value.map(serialize).join(',')}]`;
  return `{${Object.entries(value).filter(([, entry]) => entry !== undefined)
    .map(([key, entry]) => `${serialize(key)}:${serialize(entry)}`).join(',')}}`;
}

export function exportAnimation(model) {
  const { duration, tracks } = compileTimeline(model);
  const snapshot = {
    version: 1,
    duration,
    tracks: tracks.map(({ targetId, property, keyframes }) => ({
      targetId, property,
      keyframes: keyframes.map(({ time, value, easeToNext, ease }) => ({ time, value, easeToNext, ease })),
    })),
  };
  return `// Generated by Motion Engine. Self-contained browser ES module.\n${exportRuntime()}
const model = ${serialize(snapshot)};

export function createAnimation(root, options) {
  return createAnimationInstance(model, root, options);
}
`;
}
